#!/usr/bin/env python3
"""Generate Swift theme tokens from docs/design/system/tokens.json.

Writes two files:
  SelvoCore/Sources/SelvoCore/Tokens.generated.swift  (plain values, no SwiftUI)
  Selvo/Theme/ThemeColors.generated.swift             (SwiftUI Color catalog)

Run with --check to fail when the committed files are out of date (CI does this).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "docs/design/system/tokens.json"
CORE_OUT = ROOT / "SelvoCore/Sources/SelvoCore/Tokens.generated.swift"
APP_OUT = ROOT / "Selvo/Theme/ThemeColors.generated.swift"
HEADER = "// Generated by scripts/gen_tokens.py from docs/design/system/tokens.json. Do not edit by hand.\n"


def camel(name: str) -> str:
    parts = re.split(r"[-_]", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    # Swift identifiers cannot start with a digit; space-1 becomes space1.
    return out


def px(value: str) -> float:
    return float(value.replace("px", ""))


def em(value) -> float:
    if value is None:
        return 0.0
    return float(str(value).replace("em", ""))


def resolve_colors(tokens):
    by_name = {t["name"]: t["value"] for t in tokens}

    def resolve(value):
        if isinstance(value, str):
            ref = re.fullmatch(r"\{(.+)\}", value)
            if ref:
                return resolve(by_name[ref.group(1)])
            return {"night": value, "day": value}
        return value

    return [(t["name"], resolve(t["value"])) for t in tokens]


def hex_literal(h: str) -> str:
    h = h.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"expected #rrggbb, got {h}")
    return f"0x{h.upper()}"


def parse_shadow(value: str):
    m = re.fullmatch(
        r"\s*(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)px(?: (\d+)px)? rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)\s*",
        value,
    )
    if not m:
        raise ValueError(f"cannot parse shadow {value}")
    x, y, blur, spread, r, g, b, a = m.groups()
    rgb = (int(r) << 16) | (int(g) << 8) | int(b)
    return {
        "x": float(x), "y": float(y), "blur": float(blur), "spread": float(spread or 0),
        "color": f"RGBA(hex: 0x{rgb:06X}, alpha: {float(a)})",
    }


def generate():
    data = json.loads(TOKENS.read_text())
    colors = resolve_colors(data["color"]["tokens"])

    core = [HEADER, "", "// swiftlint:disable all", ""]

    # Palette
    core.append("public struct Palette: Equatable, Sendable {")
    for name, _ in colors:
        core.append(f"    public let {camel(name)}: RGBA")
    core.append("")
    for theme in ("night", "day"):
        core.append(f"    public static let {theme} = Palette(")
        lines = [f"        {camel(name)}: RGBA(hex: {hex_literal(v[theme])})" for name, v in colors]
        core.append(",\n".join(lines))
        core.append("    )")
        core.append("")
    core.append("    /// Look a color up by its token name in tokens.json (for example \"surface-raised\").")
    core.append("    public func color(named name: String) -> RGBA? {")
    core.append("        switch name {")
    for name, _ in colors:
        core.append(f"        case \"{name}\": return {camel(name)}")
    core.append("        default: return nil")
    core.append("        }")
    core.append("    }")
    core.append("")
    core.append("    public static let tokenNames: [String] = [" + ", ".join(f'"{n}"' for n, _ in colors) + "]")
    core.append("}")
    core.append("")

    # Spacing
    core.append("public enum Spacing {")
    for t in data["spacing"]["tokens"]:
        core.append(f"    public static let {camel(t['name'])}: Double = {px(t['value'])}")
    core.append("}")
    core.append("")

    # Radius
    core.append("public enum Radius {")
    for t in data["radius"]["tokens"]:
        name = camel(t["name"].replace("radius-", ""))
        core.append(f"    public static let {name}: Double = {px(t['value'])}")
    core.append("}")
    core.append("")

    # Type
    core.append("public enum TypeScale {")
    all_styles = []
    for group in data["type"]["groups"]:
        for s in group["styles"]:
            all_styles.append(s["name"])
            core.append(
                f"    public static let {camel(s['name'])} = TypeStyle(name: \"{s['name']}\", "
                f"size: {px(s['fontSize'])}, lineHeight: {px(s['lineHeight'])}, "
                f"weight: {int(s['fontWeight'])}, tracking: {em(s.get('letterSpacing'))})"
            )
    core.append("    public static let all: [TypeStyle] = [" + ", ".join(camel(n) for n in all_styles) + "]")
    core.append("}")
    core.append("")

    # Shadows
    core.append("public enum Shadows {")
    for t in data["shadow"]["tokens"]:
        for theme in ("night", "day"):
            s = parse_shadow(t["value"][theme])
            core.append(
                f"    public static let {camel(t['name'])}{theme.capitalize()} = ShadowToken("
                f"x: {s['x']}, y: {s['y']}, blur: {s['blur']}, spread: {s['spread']}, color: {s['color']})"
            )
    core.append("}")
    core.append("")

    # App side: SwiftUI colors
    app = [HEADER, "", "import SwiftUI", "import SelvoCore", ""]
    app.append("/// Every color token as a SwiftUI Color for one theme.")
    app.append("struct ThemeColors {")
    for name, _ in colors:
        app.append(f"    let {camel(name)}: Color")
    app.append("")
    app.append("    init(_ palette: Palette) {")
    for name, _ in colors:
        app.append(f"        {camel(name)} = Color(palette.{camel(name)})")
    app.append("    }")
    app.append("}")
    app.append("")

    return "\n".join(core).rstrip() + "\n", "\n".join(app).rstrip() + "\n"


def main():
    core, app = generate()
    if "--check" in sys.argv:
        stale = [p for p, c in ((CORE_OUT, core), (APP_OUT, app)) if not p.exists() or p.read_text() != c]
        if stale:
            print("Generated token files are out of date. Run: python3 scripts/gen_tokens.py")
            for p in stale:
                print("  " + str(p.relative_to(ROOT)))
            sys.exit(1)
        print("Token files are up to date.")
        return
    CORE_OUT.write_text(core)
    APP_OUT.write_text(app)
    print("Wrote " + str(CORE_OUT.relative_to(ROOT)) + " and " + str(APP_OUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
